"""Run the implemented Cervical Cancer Data Mining workflow in order."""

import importlib.util
import hashlib
from importlib.metadata import version
import subprocess
import sys
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent
SCRIPTS = [
    ("Data integrity verification", "src/verify_data_integrity.py"),
    ("Clustering preprocessing", "src/clustering_preprocessing.py"),
    ("K-Means experiment", "src/kmeans_experiment.py"),
    ("DBSCAN experiment", "src/dbscan_experiment.py"),
    ("Comparative evaluation", "src/compare_clustering.py"),
]
REQUIRED_PACKAGES = {
    "pandas": "pandas",
    "numpy": "numpy",
    "matplotlib": "matplotlib",
    "sklearn": "scikit-learn",
}
MINIMUM_PYTHON = (3, 12)
MANIFEST_PATH = PROJECT_ROOT / "outputs" / "results" / "workflow_run_manifest.md"
RAW_PATH = PROJECT_ROOT / "data" / "raw" / "risk_factors_cervical_cancer.csv"
FEATURES_PATH = PROJECT_ROOT / "data" / "processed" / "PROVISIONAL_clustering_features.csv"


def sha256_file(path):
    """Compute a file digest for read-only reproducibility checks."""
    digest = hashlib.sha256()
    with path.open("rb") as file_handle:
        for chunk in iter(lambda: file_handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def write_run_manifest(completed):
    """Record the environment and settings used by the completed workflow."""
    package_versions = {
        "pandas": version("pandas"),
        "numpy": version("numpy"),
        "matplotlib": version("matplotlib"),
        "scikit-learn": version("scikit-learn"),
    }
    manifest = [
        "# Workflow Run Manifest\n\n",
        "Generated by `run_project.py` after all workflow steps completed successfully. "
        "The values below are the current configurable baseline; they do not represent teacher approval.\n\n",
        "## Execution environment\n\n",
        f"- Python: `{sys.version.split()[0]}`\n",
        f"- Executable: `{sys.executable}`\n",
        *[f"- {name}: `{package_version}`\n" for name, package_version in package_versions.items()],
        f"- Raw CSV SHA-256: `{sha256_file(RAW_PATH)}`\n",
        f"- Processed matrix SHA-256: `{sha256_file(FEATURES_PATH)}`\n",
        "\n## Workflow configuration\n\n",
        "- Preprocessing features: nine columns listed in `outputs/results/clustering_preprocessing_audit.md`\n",
        "- Missing-value policy: median\n",
        "- Duplicate policy: remove exact duplicate copies from the modeling copy\n",
        "- Scaling: standardization using population standard deviation\n",
        "- K-Means: K=2–6; 10 initializations per K; seed 42; maximum 300 iterations; centroid-shift tolerance 0.0001\n",
        "- DBSCAN: Euclidean distance; `eps`=1.0, 1.5, 2.0, 2.5; `min_samples`=5, 10; fixed input row order; `n_jobs=1`\n",
        "- Comparison: saved assignments, five best-SSE K-Means configurations, and all eight DBSCAN configurations\n",
        "\n## Completed steps\n\n",
        *[f"- {label}\n" for label in completed],
        "\nAll preprocessing choices remain provisional. See the individual experiment reports for detailed measured results.\n",
    ]
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_PATH.write_text("".join(manifest), encoding="utf-8")


def main():
    """Check dependencies, then stop at the first failed workflow step."""
    if sys.version_info < MINIMUM_PYTHON:
        print(
            "Python 3.12 or newer is required by the documented dependency versions; "
            f"found {sys.version.split()[0]}.",
            file=sys.stderr,
        )
        return 1

    missing = [
        package_name
        for module_name, package_name in REQUIRED_PACKAGES.items()
        if importlib.util.find_spec(module_name) is None
    ]
    if missing:
        print("Missing required Python package(s): " + ", ".join(missing), file=sys.stderr)
        print("Install them in the active environment before running this workflow.", file=sys.stderr)
        return 1

    completed = []
    print(f"Project directory: {PROJECT_ROOT}", flush=True)
    print(f"Python executable: {sys.executable}", flush=True)
    print(
        "Environment: "
        + ", ".join(
            f"{name} {version(distribution)}"
            for name, distribution in (
                ("pandas", "pandas"),
                ("NumPy", "numpy"),
                ("Matplotlib", "matplotlib"),
                ("scikit-learn", "scikit-learn"),
            )
        ),
        flush=True,
    )

    for index, (label, relative_script) in enumerate(SCRIPTS, start=1):
        script_path = PROJECT_ROOT / relative_script
        if not script_path.is_file():
            print(f"Cannot run {relative_script}: script file does not exist.", file=sys.stderr)
            print("Successful steps: " + (", ".join(completed) if completed else "none"), file=sys.stderr)
            return 1

        print(f"\n[{index}/{len(SCRIPTS)}] {label}: {relative_script}", flush=True)
        result = subprocess.run(
            [sys.executable, str(script_path)],
            cwd=PROJECT_ROOT,
            check=False,
        )
        if result.returncode != 0:
            print(
                f"FAILED: {relative_script} exited with code {result.returncode}.",
                file=sys.stderr,
            )
            print("Successful steps: " + (", ".join(completed) if completed else "none"), file=sys.stderr)
            return result.returncode or 1
        completed.append(label)
        print(f"Completed: {label}", flush=True)

    write_run_manifest(completed)
    print("\nWorkflow completed successfully.", flush=True)
    print("Successful steps: " + ", ".join(completed), flush=True)
    print(f"Environment and configuration manifest: {MANIFEST_PATH.relative_to(PROJECT_ROOT)}", flush=True)
    print("Existing generated reports, tables, graphs, and the provisional matrix were regenerated.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
